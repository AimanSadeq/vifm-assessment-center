import { notFound } from "next/navigation";
import { Boxes, Building2, Download, FileArchive, FolderOpen } from "lucide-react";
import { requireRole, isAuthorizationError } from "@/lib/ara/auth-guards";
import { loadFiledReports, ZIP_MAX_FILES, type FiledReport } from "@/lib/bespoke/report-filing";
import { BackLink } from "@/components/shared/back-link";

export const dynamic = "force-dynamic";
export const metadata = { title: "Filed reports · VIFM" };

// Every bundle report PDF kept on generation (00237), foldered the way it is
// stored: company, then assessment, then candidate. Each company and each
// assessment downloads as one ZIP with the same folders.

type BundleGroup = { bundleId: string; bundleName: string; rows: FiledReport[] };
type OrgGroup = { key: string; orgName: string; bundles: BundleGroup[]; count: number };

function groupReports(rows: FiledReport[]): OrgGroup[] {
  const orgs = new Map<string, OrgGroup>();
  for (const r of rows) {
    const key = r.organizationId ?? "unassigned";
    let org = orgs.get(key);
    if (!org) {
      org = { key, orgName: r.orgName, bundles: [], count: 0 };
      orgs.set(key, org);
    }
    let bundle = org.bundles.find((b) => b.bundleId === r.bundleId);
    if (!bundle) {
      bundle = { bundleId: r.bundleId, bundleName: r.bundleName, rows: [] };
      org.bundles.push(bundle);
    }
    bundle.rows.push(r);
    org.count += 1;
  }
  const byName = (a: string, b: string) => a.localeCompare(b, "en", { sensitivity: "base" });
  const out = Array.from(orgs.values());
  for (const o of out) {
    o.bundles.sort((a, b) => byName(a.bundleName, b.bundleName));
    for (const b of o.bundles) b.rows.sort((x, y) => byName(x.candidateName, y.candidateName) || byName(x.kindLabel, y.kindLabel));
  }
  // Unassigned last, companies alphabetical.
  return out.sort((a, b) => (a.key === "unassigned" ? 1 : b.key === "unassigned" ? -1 : byName(a.orgName, b.orgName)));
}

function fmtDate(s: string): string {
  try {
    return new Date(s).toLocaleDateString("en-GB", { day: "numeric", month: "short", year: "numeric" });
  } catch {
    return "-";
  }
}

function fmtSize(bytes: number | null): string {
  if (bytes == null) return "-";
  if (bytes < 1024) return `${bytes} B`;
  if (bytes < 1024 * 1024) return `${Math.round(bytes / 1024)} KB`;
  return `${(bytes / (1024 * 1024)).toFixed(1)} MB`;
}

function ZipLink({ href, label }: { href: string; label: string }) {
  return (
    <a
      href={href}
      className="inline-flex items-center gap-1.5 rounded-md border border-border bg-background px-2.5 py-1 text-xs font-medium text-foreground hover:bg-muted"
    >
      <FileArchive className="h-3.5 w-3.5" />
      {label}
    </a>
  );
}

export default async function FiledReportsPage() {
  try {
    await requireRole(["admin"]);
  } catch (e) {
    if (isAuthorizationError(e)) notFound();
    throw e;
  }

  const rows = await loadFiledReports();
  const groups = groupReports(rows);

  return (
    <div className="space-y-6">
      <BackLink href="/admin/bespoke/reports" label="Bespoke Reports" />
      <div>
        <h1 className="text-2xl font-bold">Filed reports</h1>
        <p className="mt-1 max-w-2xl text-sm text-muted-foreground">
          Every bundle report generated by the team is kept here, filed by company and assessment. Generating a
          report again replaces the filed copy. Each ZIP holds up to {ZIP_MAX_FILES} reports.
        </p>
      </div>

      {groups.length === 0 ? (
        <section className="rounded-xl border bg-card p-5">
          <div className="flex items-center gap-2">
            <FolderOpen className="h-4 w-4 text-muted-foreground" />
            <p className="text-sm text-muted-foreground">
              No filed reports yet. A report is filed the first time a team member generates it.
            </p>
          </div>
        </section>
      ) : (
        groups.map((org) => (
          <section key={org.key} className="rounded-xl border bg-card p-5">
            <div className="flex flex-wrap items-center justify-between gap-2">
              <div className="flex items-center gap-2">
                <Building2 className="h-4 w-4 text-[#5391D5]" />
                <h2 className="text-sm font-semibold text-foreground">{org.orgName}</h2>
                <span className="text-xs text-muted-foreground">
                  {org.count} {org.count === 1 ? "report" : "reports"}
                </span>
              </div>
              <ZipLink href={`/api/admin/bundle-reports/zip?org=${encodeURIComponent(org.key)}`} label="Download all (ZIP)" />
            </div>

            <div className="mt-4 space-y-5">
              {org.bundles.map((b) => (
                <div key={b.bundleId}>
                  <div className="flex flex-wrap items-center justify-between gap-2 border-b pb-2">
                    <div className="flex items-center gap-2">
                      <Boxes className="h-3.5 w-3.5 text-muted-foreground" />
                      <h3 className="text-sm font-medium text-foreground">{b.bundleName}</h3>
                      <span className="text-xs text-muted-foreground">{b.rows.length}</span>
                    </div>
                    <ZipLink
                      href={`/api/admin/bundle-reports/zip?org=${encodeURIComponent(org.key)}&bundle=${encodeURIComponent(b.bundleId)}`}
                      label="Download all (ZIP)"
                    />
                  </div>
                  <div className="overflow-x-auto">
                    <table className="w-full text-sm">
                      <thead>
                        <tr className="border-b text-left text-xs uppercase tracking-wide text-muted-foreground">
                          <th className="py-2 pr-3">Candidate</th>
                          <th className="py-2 pr-3">Email</th>
                          <th className="py-2 pr-3">Report</th>
                          <th className="py-2 pr-3">Filed</th>
                          <th className="py-2 pr-3">Size</th>
                          <th className="py-2 pr-3 text-end">File</th>
                        </tr>
                      </thead>
                      <tbody>
                        {b.rows.map((r) => (
                          <tr key={r.id} className="border-b last:border-0">
                            <td className="py-2 pr-3 font-medium text-foreground">{r.candidateName}</td>
                            <td className="py-2 pr-3 text-muted-foreground">{r.candidateEmail ?? "-"}</td>
                            <td className="py-2 pr-3">{r.kindLabel}</td>
                            <td className="py-2 pr-3 whitespace-nowrap text-muted-foreground">{fmtDate(r.createdAt)}</td>
                            <td className="py-2 pr-3 whitespace-nowrap text-muted-foreground">{fmtSize(r.sizeBytes)}</td>
                            <td className="py-2 pr-3 text-end">
                              <a
                                href={`/api/admin/bundle-reports/file/${r.id}`}
                                className="inline-flex items-center gap-1 text-xs font-medium text-[#5391D5] hover:underline"
                              >
                                <Download className="h-3.5 w-3.5" />
                                Download
                              </a>
                            </td>
                          </tr>
                        ))}
                      </tbody>
                    </table>
                  </div>
                </div>
              ))}
            </div>
          </section>
        ))
      )}
    </div>
  );
}
